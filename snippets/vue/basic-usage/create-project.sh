# Create new Vue project with Bun
bun create vue@latest my-vue-app

# Navigate to project
cd my-vue-app

# Install dependencies
bun install

# Start development server
bun dev

# Build for production
bun build

# Preview production build
bun preview

# Alternative: Create with specific features
bun create vue@latest my-vue-app -- --typescript --router --pinia --vitest --eslint