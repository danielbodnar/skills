// 6. File Watcher System
class ThemerWatcher {
  constructor(options = {}) {
    this.options = {
      watchPaths: ['src/colors/**/*.js'],
      templates: ['vim', 'vscode'],
      outputDir: './themes',
      debounceMs: 300,
      ...options
    }

    this.watcher = null
    this.generateTimeout = null
  }

  start() {
    console.log('Starting Themer file watcher...')

    this.watcher = chokidar.watch(this.options.watchPaths, {
      ignored: /node_modules/,
      persistent: true,
      ignoreInitial: true
    })

    this.watcher
      .on('change', (path) => this.handleFileChange(path))
      .on('add', (path) => this.handleFileChange(path))
      .on('unlink', (path) => this.handleFileDelete(path))
      .on('error', (error) => console.error('Watcher error:', error))

    console.log(`Watching: ${this.options.watchPaths.join(', ')}`)
  }

  stop() {
    if (this.watcher) {
      this.watcher.close()
      console.log('Themer file watcher stopped')
    }
  }

  handleFileChange(filePath) {
    console.log(`File changed: ${filePath}`)

    // Debounce rapid changes
    if (this.generateTimeout) {
      clearTimeout(this.generateTimeout)
    }

    this.generateTimeout = setTimeout(() => {
      this.generateThemes(filePath)
    }, this.options.debounceMs)
  }

  handleFileDelete(filePath) {
    console.log(`File deleted: ${filePath}`)
    // Could trigger cleanup of related generated files
  }

  async generateThemes(triggerFile) {
    try {
      console.log(`Regenerating themes (triggered by ${triggerFile})...`)

      const { ThemerAPI } = require('./api-usage')
      const api = new ThemerAPI()

      // Determine which color set to use based on trigger file
      const colorSetPath = this.resolveColorSetPath(triggerFile)
      const colorSet = await api.loadColorSet(colorSetPath)

      await api.generateThemes(
        colorSet,
        this.options.templates,
        this.options.outputDir
      )

      console.log('✓ Themes regenerated successfully')
    } catch (error) {
      console.error('✗ Theme regeneration failed:', error.message)
    }
  }

  resolveColorSetPath(triggerFile) {
    // Logic to determine which color set file to use
    // Could be the trigger file itself or a main color set file
    return triggerFile.endsWith('.js') ? triggerFile : 'src/colors/main.js'
  }
}

