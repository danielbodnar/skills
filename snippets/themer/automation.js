// 2. Gulp Integration
class ThemerGulpTasks {
  static register(gulpInstance = gulp) {
    // Generate themes task
    gulpInstance.task('themes:generate', () => {
      return this.generateThemes()
    })

    // Watch for color set changes
    gulpInstance.task('themes:watch', () => {
      return gulpInstance.watch([
        'src/colors/*.js',
        'src/themes/*.js'
      ], gulpInstance.series('themes:generate'))
    })

    // Validate color sets
    gulpInstance.task('themes:validate', () => {
      return this.validateColorSets()
    })

    // Clean generated themes
    gulpInstance.task('themes:clean', () => {
      return this.cleanThemes()
    })

    // Build all themes
    gulpInstance.task('themes:build', gulpInstance.series(
      'themes:clean',
      'themes:validate',
      'themes:generate'
    ))
  }

  static generateThemes() {
    return new Promise((resolve, reject) => {
      const child = spawn('themer', [
        '-c', 'src/colors/main.js',
        '-t', 'vim',
        '-t', 'vscode',
        '-t', 'iterm',
        '-o', 'dist/themes'
      ], { stdio: 'inherit' })

      child.on('close', (code) => {
        if (code === 0) {
          console.log('✓ Themes generated successfully')
          resolve()
        } else {
          reject(new Error(`Theme generation failed with code ${code}`))
        }
      })
    })
  }

  static async validateColorSets() {
    const colorSetFiles = await this.findColorSetFiles()

    for (const file of colorSetFiles) {
      try {
        const colorSet = require(path.resolve(file))
        const validation = this.validateColorSet(colorSet)

        if (!validation.valid) {
          throw new Error(`Invalid color set in ${file}: ${validation.errors.join(', ')}`)
        }

        if (validation.warnings.length > 0) {
          console.warn(`Warnings in ${file}:`, validation.warnings)
        }

        console.log(`✓ Color set ${file} is valid`)
      } catch (error) {
        throw new Error(`Validation failed for ${file}: ${error.message}`)
      }
    }
  }

  static async cleanThemes() {
    const { rimraf } = require('rimraf')
    await rimraf('dist/themes/*')
    console.log('✓ Cleaned theme output directory')
  }

  static async findColorSetFiles() {
    const glob = require('glob')
    return glob.sync('src/colors/*.js')
  }

  static validateColorSet(colorSet) {
    // Validation logic from api-usage.js
    const errors = []
    const warnings = []

    if (!colorSet.name) errors.push('Missing name')
    if (!colorSet.colors) errors.push('Missing colors')

    return { valid: errors.length === 0, errors, warnings }
  }
}

// 3. Webpack Integration
class ThemerWebpackPlugin {
  constructor(options = {}) {
    this.options = {
      colorSetPath: './src/colors.js',
      templates: ['css'],
      outputPath: './src/generated',
      ...options
    }
  }

  apply(compiler) {
    compiler.hooks.beforeCompile.tapAsync('ThemerWebpackPlugin', (params, callback) => {
      this.generateThemes()
        .then(() => callback())
        .catch(callback)
    })

    if (this.options.watch) {
      compiler.hooks.watchRun.tapAsync('ThemerWebpackPlugin', (compiler, callback) => {
        const changedFiles = Object.keys(compiler.watchFileSystem.watcher.mtimes)

        if (changedFiles.some(file => file.includes(this.options.colorSetPath))) {
          this.generateThemes()
            .then(() => callback())
            .catch(callback)
        } else {
          callback()
        }
      })
    }
  }

  async generateThemes() {
    const { ThemerAPI } = require('./api-usage')
    const api = new ThemerAPI()

    try {
      const colorSet = await api.loadColorSet(this.options.colorSetPath)
      await api.generateThemes(
        colorSet,
        this.options.templates,
        this.options.outputPath
      )
      console.log('✓ Themes generated by webpack plugin')
    } catch (error) {
      console.error('✗ Theme generation failed:', error.message)
      throw error
    }
  }
}

// 4. Vite Integration
function themerVitePlugin(options = {}) {
  const config = {
    colorSetPath: './src/colors.js',
    templates: ['css'],
    outputPath: './src/generated',
    ...options
  }

  let api

  return {
    name: 'themer',
    configResolved() {
      const { ThemerAPI } = require('./api-usage')
      api = new ThemerAPI()
    },
    async buildStart() {
      await this.generateThemes()
    },
    async handleHotUpdate({ file, server }) {
      if (file.includes(config.colorSetPath)) {
        await this.generateThemes()
        server.ws.send({
          type: 'full-reload'
        })
      }
    },
    async generateThemes() {
      try {
        const colorSet = await api.loadColorSet(config.colorSetPath)
        await api.generateThemes(colorSet, config.templates, config.outputPath)
        console.log('✓ Themes generated by Vite plugin')
      } catch (error) {
        console.error('✗ Theme generation failed:', error.message)
      }
    }
  }
}

